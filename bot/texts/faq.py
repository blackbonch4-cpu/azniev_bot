def get_faq_questions():
    """Получить список вопросов"""
    return [q for q, a in FAQ_LIST]


def get_faq_answer(question_index: int) -> str:
    """
    Получить ответ на вопрос по индексу

    Args:
        question_index: Индекс вопроса (начиная с 0)

    Returns:
        Ответ на вопрос или сообщение об ошибке
    """
    try:
        return FAQ_LIST[question_index][1]
    except IndexError:
        return "Вопрос не найден"


def get_faq_by_text(question_text: str) -> Optional[str]:
    """
    Получить ответ на вопрос по тексту вопроса

    Args:
        question_text: Текст вопроса

    Returns:
        Ответ на вопрос или None если не найдено
    """
    for q, a in FAQ_LIST:
        if q == question_text:
            return a
    return None
